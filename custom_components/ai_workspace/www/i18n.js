const ALIASES = {
  "zh-cn": "zh-Hans",
  "zh-sg": "zh-Hans",
  zh: "zh-Hans",
  "zh-tw": "zh-Hant",
  "zh-hk": "zh-Hant",
  "zh-mo": "zh-Hant",
};

export function pickLanguage(raw) {
  const value = String(raw || "en").replaceAll("_", "-");
  const lower = value.toLowerCase();
  if (I18N[value]) return value;
  if (ALIASES[lower]) return ALIASES[lower];
  const short = value.split("-")[0];
  if (I18N[short]) return short;
  if (ALIASES[short]) return ALIASES[short];
  return "en";
}

export function stringsFor(lang) {
  const code = pickLanguage(lang);
  return { ...I18N.en, ...(I18N[code] || {}) };
}
